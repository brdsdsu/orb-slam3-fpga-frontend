import argparse
import numpy as np
from tqdm import tqdm


# Two of the output files are structured the following way:
#   window_stream.hex, the pixel data:
#   First the 8-bit pixel value, then 1 if its the first pixel, 0 otherwise
# 
#   window_expected contains WIDTH-(WINDOWSIZE-1) x HEIGHT-(WINDOWSIZE-1) lines, each structured like:
#   Example line:   0003 0003 00 01 02 03 04 05 06 .. 80 81 82 83 84 85 86 00 01 02 03 04 05 06
#                     |    |  |______________________________________________________________|
#          x-coordinate  y-cord         WINDOWSIZE * WINDOWSIZE patch in row-major order
#
# This script also generates a third file named window_test_params_pkg.vhd with the same parameters that created the
# files mentioned above. this keeps the testing consistent, so changing the input image size also changes the test.

def write_test_params_pkg(path: str, width: int, height: int, n: int):
    """Write a VHDL package with the test parameters used to generate vectors.

    The testbench `use`s this package to ensure its constants match what
    the Python generator actually produced.
    """
    content = f"""-- AUTO-GENERATED by window_nxn_generator.py. DO NOT EDIT BY HAND.
-- Regenerate by running:
--   py window_nxn_generator.py -W {width} -H {height} -n {n}

library ieee;
use ieee.std_logic_1164.all;

package window_test_params_pkg is
    constant TEST_IMG_WIDTH  : natural := {width};
    constant TEST_IMG_HEIGHT : natural := {height};
    constant TEST_N          : natural := {n};
end package;
    """
    with open(path, 'w') as f:
        f.write(content)

def generate_image(width: int, height: int, mode: str, seed: int) -> np.ndarray:
    """Generate a test image of the given size.

    Modes:
      - "random":     uniform random pixels
      - "gradient":   x + y, useful for visually inspecting window contents
      - "checker":    alternating 0/255 pattern, exercises sharp transitions
      - "sequence":   pixel value = (row * width + col) mod 256, makes each
                      pixel uniquely identifiable for debugging
    """
    if mode == "random":
        rng = np.random.default_rng(seed)
        return rng.integers(0, 256, size=(height, width), dtype=np.uint8)
    elif mode == "gradient":
        y, x = np.meshgrid(np.arange(height), np.arange(width), indexing='ij')
        return ((x + y) % 256).astype(np.uint8)
    elif mode == "checker":
        y, x = np.meshgrid(np.arange(height), np.arange(width), indexing='ij')
        return (((x + y) % 2) * 255).astype(np.uint8)
    elif mode == "sequence":
        return (np.arange(width * height).reshape(height, width) % 256).astype(np.uint8)
    else:
        raise ValueError(f"Unknown mode: {mode}")


def extract_expected_windows(image: np.ndarray, n: int):
    """Slide an n×n window across the image in raster order.

    Yields (x, y, patch) for every center position where the full window fits
    within the image bounds. Matches the DUT's o_valid policy: borders of
    width n//2 are skipped.

    Patch layout: patch[row, col] where row 0 is the top of the window
    (oldest line) and col 0 is the leftmost column. This matches the
    indexing convention in window_nxn.vhd.
    """
    half = n // 2
    h, w = image.shape

    # Iterate in raster order over valid center positions only.
    # The DUT emits outputs in this same order, so the testbench can
    # compare position-by-position without sorting.
    for y in tqdm(range(half, h - half), desc="Slide an n×n window across the image in raster order"):
        for x in range(half, w - half):
            patch = image[y - half : y + half + 1, x - half : x + half + 1]
            yield (x, y, patch)


def write_pixel_stream(path: str, image: np.ndarray):
    """Write the image as one pixel per line in raster order.

    Format: one hex byte per line. The first byte of each frame should
    be preceded by an SOF marker — we encode that in a separate column.
    """
    h, w = image.shape
    with open(path, 'w') as f:
        for y in tqdm(range(h), desc="Write the image as one pixel per line in raster order"):
            for x in range(w):
                # sof = 1 only on the very first pixel of the frame
                sof = 1 if (x == 0 and y == 0) else 0
                f.write(f"{int(image[y, x]):02x} {sof}\n")


def write_expected_windows(path: str, image: np.ndarray, n: int):
    """Write the expected DUT outputs, one window per line.

    Format per line:
      x_hex y_hex p00 p01 ... p(N-1)(N-1)
    where the patch is flattened in row-major order (row 0 first, then row 1, ...).
    Coordinates are 4 hex chars (16-bit), pixels are 2 hex chars (8-bit).
    """
    with open(path, 'w') as f:
        for x, y, patch in tqdm(extract_expected_windows(image, n), desc="Write the expected DUT outputs, one window per line"):
            parts = [f"{x:04x}", f"{y:04x}"]
            for row in range(n):
                for col in range(n):
                    parts.append(f"{int(patch[row, col]):02x}")
            f.write(" ".join(parts) + "\n")


def main():
    parser = argparse.ArgumentParser(
        description="Generate test stimulus and expected outputs for window_nxn.vhd. Large -W or -H values can lead to long generating times."
    )
    parser.add_argument("-W", "--width", type=int, default=32,
                        help="Image width in pixels (default: 32)")
    parser.add_argument("-H", "--height", type=int, default=32,
                        help="Image height in pixels (default: 32)")
    parser.add_argument("-n", "--window-size", type=int, default=7,
                        help="Window size N, must be odd (default: 7)")
    parser.add_argument("-m", "--mode", type=str, default="sequence",
                        choices=["random", "gradient", "checker", "sequence"],
                        help="Image content pattern (default: sequence)")
    parser.add_argument("-s", "--seed", type=int, default=0,
                        help="RNG seed for random mode (default: 0)")
    args = parser.parse_args()

    if args.window_size % 2 != 1:
        parser.error(f"Window size must be odd, got {args.window_size}")
    if args.window_size > min(args.width, args.height):
        parser.error(f"Window size {args.window_size} exceeds image dimensions "
                     f"{args.width}x{args.height}")

    image = generate_image(args.width, args.height, args.mode, args.seed)
    write_pixel_stream("window_stream.hex", image)
    write_expected_windows("window_expected.hex", image, args.window_size)
    write_test_params_pkg("window_test_params_pkg.vhd", args.width, args.height, args.window_size)

    n_valid = (args.height - args.window_size + 1) * (args.width - args.window_size + 1)
    print(f"Generated {args.width}x{args.height} image (mode={args.mode}, seed={args.seed})")
    print(f"  Pixel stream:     window_stream.hex  ({args.width * args.height} pixels)")
    print(f"  Expected windows: window_expected.hex  ({n_valid} valid center positions)")
    print(f"  Test parameters:  window_test_params_pkg.vhd")


if __name__ == "__main__":
    main()